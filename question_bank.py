def _make_paper(exam, set_no, count, duration):
    """Build a balanced paper with questions from all three subjects."""
    questions = []
    per_subject = count // 3
    remainder = count % 3
    subjects = ("Physics", "Chemistry", "Mathematics")

    for subject_index, subject in enumerate(subjects):
        take = per_subject + (1 if subject_index < remainder else 0)
        subject_questions = QUESTION_BANK[subject]
        # Rotate the starting position so papers are not all identical.
        start = ((set_no - 1) * take) % len(subject_questions)

        for offset in range(take):
            original = subject_questions[(start + offset) % len(subject_questions)]
            question = dict(original)
            question["options"] = list(original["options"])
            question["id"] = f"{subject[:3].upper()}-{exam.upper()}-{set_no}-{len(questions) + 1}"
            questions.append(question)

    # Interleave subjects so each paper feels like a mixed exam.
    balanced = []
    buckets = {subject: [] for subject in subjects}
    for question in questions:
        buckets[question["subject"]].append(question)
    while any(buckets.values()):
        for subject in subjects:
            if buckets[subject]:
                balanced.append(buckets[subject].pop(0))

    return {
        "title": (
            f"JEE Main Mock Test {set_no}"
            if exam == "main"
            else f"JEE Advanced Practice Paper {set_no}"
        ),
        "duration": duration,
        "questions": balanced,
    }


QUESTION_SETS = {
    "main": {
        number: _make_paper("main", number, 75, 180)
        for number in range(1, 11)
    },
    "advanced": {
        number: _make_paper("advanced", number, 54, 180)
        for number in range(1, 6)
    },
}

# Fail early with a clear message if the file is accidentally edited incorrectly.
for _subject in ("Physics", "Chemistry", "Mathematics"):
    if len(QUESTION_BANK.get(_subject, [])) != 100:
        raise ValueError(f"{_subject} must contain exactly 100 questions.")
    for _number, _question in enumerate(QUESTION_BANK[_subject], start=1):
        if len(_question.get("options", [])) != 4:
            raise ValueError(f"{_subject} question {_number} must have four options.")
        if _question.get("answer") not in range(4):
            raise ValueError(f"{_subject} question {_number} has an invalid answer index.")

for _exam, _papers in QUESTION_SETS.items():
    for _set_number, _paper in _papers.items():
        _expected = 75 if _exam == "main" else 54
        if len(_paper["questions"]) != _expected:
            raise ValueError(f"{_exam} paper {_set_number} must contain {_expected} questions.")

del _subject, _number, _question, _exam, _papers, _set_number, _paper, _expected
